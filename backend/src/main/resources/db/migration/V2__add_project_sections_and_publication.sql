-- V2: Add project sections table and publication status to projects
-- This migration adds support for dynamic sections in project details and publication workflow

-- Create project_sections table
CREATE TABLE project_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    title VARCHAR(255) NOT NULL,
    icon VARCHAR(100),
    content_type VARCHAR(50) NOT NULL,
    content TEXT,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_project_section_project FOREIGN KEY (project_id) REFERENCES projects(id) ON DELETE CASCADE
);

-- Create index for ordering
CREATE INDEX idx_project_sections_project_order ON project_sections(project_id, display_order);

-- Add publication_status column to projects table
ALTER TABLE projects ADD COLUMN IF NOT EXISTS publication_status VARCHAR(20) NOT NULL DEFAULT 'DRAFT';

-- Add display_order column to projects table
ALTER TABLE projects ADD COLUMN IF NOT EXISTS display_order INT NOT NULL DEFAULT 0;

-- Add updated_at column to projects table
ALTER TABLE projects ADD COLUMN IF NOT EXISTS updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP;

-- Backfill existing projects: set publication_status to PUBLISHED and display_order based on id
UPDATE projects SET publication_status = 'PUBLISHED', display_order = id - 1 WHERE publication_status = 'DRAFT';

-- Create index for publication status filtering
CREATE INDEX idx_projects_publication_status ON projects(publication_status);
CREATE INDEX idx_projects_display_order ON projects(display_order);