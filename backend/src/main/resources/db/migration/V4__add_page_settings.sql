-- V4: Add page_settings table for managing page titles, descriptions, and footers

CREATE TABLE page_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_key VARCHAR(100) NOT NULL UNIQUE,
    title_fr TEXT,
    title_en TEXT,
    description_fr TEXT,
    description_en TEXT,
    footer_fr TEXT,
    footer_en TEXT,
    display_order INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_page_settings_page_key ON page_settings(page_key);
CREATE INDEX idx_page_settings_display_order ON page_settings(display_order);

