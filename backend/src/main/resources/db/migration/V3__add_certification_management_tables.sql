-- Add foreign key for issuer
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.table_constraints
        WHERE constraint_name = 'fk_certification_issuer'
        AND table_name = 'certifications'
    ) THEN
        ALTER TABLE certifications ADD CONSTRAINT fk_certification_issuer
            FOREIGN KEY (issuer_id) REFERENCES certification_issuers(id) ON DELETE SET NULL;
    END IF;
END $$;

-- Create indexes for filtering
CREATE INDEX IF NOT EXISTS idx_certifications_publication_status ON certifications(publication_status);
CREATE INDEX IF NOT EXISTS idx_certifications_display_order ON certifications(display_order);
CREATE INDEX IF NOT EXISTS idx_certifications_is_visible ON certifications(is_visible);
CREATE INDEX IF NOT EXISTS idx_certifications_issuer_id ON certifications(issuer_id);

-- Migrate existing data: issuer string -> issuer_id
-- Create issuers from existing certifications
INSERT INTO certification_issuers (name, created_at, updated_at)
SELECT DISTINCT issuer, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
FROM certifications
WHERE issuer IS NOT NULL AND issuer != ''
ON CONFLICT (name) DO NOTHING;

-- Update certifications with issuer_id
UPDATE certifications c
SET issuer_id = i.id
FROM certification_issuers i
WHERE c.issuer = i.name;

-- Backfill existing certifications: set publication_status to PUBLISHED and display_order based on id
UPDATE certifications SET publication_status = 'PUBLISHED', display_order = id - 1 WHERE publication_status = 'DRAFT';

-- Migrate existing skills from element collection to certification_skills table
-- The old certification_skills table (from @ElementCollection) will be dropped by Hibernate if we recreate
-- But we need to migrate data first
DO $$
DECLARE
    cert_record RECORD;
    skill_text TEXT;
    skill_array TEXT[];
    i INT;
BEGIN
    FOR cert_record IN SELECT id, skills FROM certifications WHERE skills IS NOT NULL AND array_length(skills, 1) > 0 LOOP
        skill_array := cert_record.skills;
        FOR i IN 1..array_length(skill_array, 1) LOOP
            skill_text := skill_array[i];
            INSERT INTO certification_skills (certification_id, name, display_order, created_at, updated_at)
            VALUES (cert_record.id, skill_text, i-1, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);
        END LOOP;
    END LOOP;
END $$;